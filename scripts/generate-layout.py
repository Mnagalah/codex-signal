#!/usr/bin/env python3
"""Compile the HTML's one grid contract into the actual menu-bar component."""
import argparse
import json
import math
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = ROOT / 'native/Sources/MenuBar/LayoutContract.generated.swift'
COPY_TARGET = ROOT / 'native/Sources/MenuBar/InterfaceCopy.generated.swift'


def read_contract(root=ROOT):
    html = (root / 'codex-status-layout.html').read_text()
    match = re.search(r'<script id="layout-contract" type="application/json">\s*(.*?)\s*</script>', html, re.S)
    if not match:
        raise ValueError('HTML is missing layout-contract')
    contract = json.loads(match.group(1))
    if contract['version'] != 1:
        raise ValueError('Unsupported grid contract version')
    for key, value in contract['metrics'].items():
        if not re.fullmatch(r'[a-z][a-z0-9-]*', key) or not isinstance(value, (float, int)) or not math.isfinite(value) or value < 0:
            raise ValueError('Invalid metric: ' + key)
    for name, grid in contract['grids'].items():
        if grid['alignItems'] not in ('center', 'stretch') or grid['alignContent'] not in ('center', 'start'):
            raise ValueError('Unsupported alignment in ' + name)
        for track in grid['columns'] + grid['rows']:
            if not (isinstance(track, (int, float)) and track >= 0 or track in ('max-content', 'minmax(0,1fr)')):
                raise ValueError('Invalid grid track in ' + name)
        if len(grid['padding']) != 4 or min(grid['padding']) < 0:
            raise ValueError('Invalid padding in ' + name)
    for role in contract['fonts'].values():
        if role['size'] not in contract['metrics'] or role['weight'] not in (400, 500, 600):
            raise ValueError('Invalid text role')
    motion = contract['popoverMotion']
    if (not all(isinstance(value, (float, int)) and math.isfinite(value) for value in motion.values())
            or motion['response'] <= 0 or motion['reducedResponse'] <= 0
            or not 0 < motion['dampingRatio'] <= 1 or motion['offset'] < 0
            or not 0 < motion['epsilon'] < 1):
        raise ValueError('Invalid popup spring')
    notice = contract["notice"]
    if notice["holdSeconds"] != 6 or notice["motionSeconds"] <= 0 or notice["width"] <= 0:
        raise ValueError("Invalid notice contract")
    return contract


def generated(contract):
    data = json.dumps(contract, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return ('// Generated by scripts/generate-layout.py from codex-status-layout.html#layout-contract.\n'
            '// Do not edit positions or sizes here; change the shared HTML contract and rebuild.\n'
            'enum CompiledLayoutContract {\n    static let json = #"""\n' + data + '\n"""#\n}\n')


def read_copy(root=ROOT):
    html = (root / 'codex-status-layout.html').read_text()
    match = re.search(r'<script id="interface-copy" type="application/json">\s*(.*?)</script>', html, re.S)
    copy = json.loads(match.group(1))
    if not all(len(pair) == 2 and all(isinstance(s, str) and s for s in pair) for pair in copy.values()):
        raise ValueError('Invalid bilingual copy')
    return copy


def generated_copy(copy):
    data = json.dumps(copy, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return '// Generated from codex-status-layout.html#interface-copy. Do not edit.\nenum CompiledInterfaceCopy {\n    static let json = #"""\n' + data + '\n"""#\n}\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generated(read_contract())
    copy = generated_copy(read_copy())
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != result:
            raise SystemExit('Native grid is stale; run scripts/generate-layout.py or scripts/build.sh')
        if not COPY_TARGET.is_file() or COPY_TARGET.read_text() != copy:
            raise SystemExit('Native interface copy is stale; rebuild')
    else:
        TARGET.write_text(result)
        COPY_TARGET.write_text(copy)
    print('Shared HTML/native grid contract is current')


if __name__ == '__main__':
    main()
